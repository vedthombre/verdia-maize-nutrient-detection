"""
Maize Leaf Nutrient-Deficiency -- Comprehensive Model Comparison
================================================================
Evaluates all five classifiers on the SAME held-out test set and
produces a unified comparison table, plots, and JSON/CSV outputs.

Models evaluated
----------------
A. SVM                 — EfficientNet-B0 features + SVM (RBF, C=selected on val)
B. Random Forest       — EfficientNet-B0 features + RF (n_estimators=selected on val)
C. K-Nearest Neighbours— EfficientNet-B0 features + KNN (k=selected on val)
D. ResNet18            — End-to-end fine-tuned (IMAGENET1K_V1 pretrain)
E. EfficientNet-B0     — Experiment 5 checkpoint (deeper fine-tuned, Exp5)

Feature extraction note (A, B, C)
-----------------------------------
SVM, RF and KNN operate on 1280-dimensional feature vectors extracted from
a FROZEN, ImageNet-pretrained EfficientNet-B0 backbone (no classifier head).
The feature extractor is shared and identical for all three classifiers.
Features were cached by train_classical_models.py.
The StandardScaler used for SVM and KNN was also fitted only on training
features (by train_classical_models.py).

EfficientNet-B0 metrics source
-------------------------------
The Experiment 5 EfficientNet-B0 metrics are RE-COMPUTED here by running
inference with the existing checkpoint to verify reproducibility.
Reference values (from deeper_finetuned_test_metrics.json):
    Accuracy: 84.29%  |  Macro F1: 0.8248  |  Weighted F1: 0.8371
If the re-computed values match (within floating point), we confirm
reproducibility and report the fresh values.

Fairness constraints enforced
------------------------------
* Same test split (70 images) for all models.
* Same class order throughout (Healthy, Magnesium, Nitrogen, Phosphorus,
  Potassium → indices 0–4).
* No test labels used during training or hyperparameter selection.
* Inference timing measured separately and consistently for each model.

Outputs
-------
results/model_comparison.json    — structured metrics for all 5 models
results/model_comparison.csv     — tabular summary (one row per model)
results/model_comparison.png     — bar-chart comparison figure
results/svm_confusion_matrix.png
results/random_forest_confusion_matrix.png
results/knn_confusion_matrix.png
(ResNet18 confusion matrix is generated by evaluate_resnet18.py)
(EfficientNet confusion matrix was generated by evaluate_deeper_finetuned.py)

Usage
-----
Run after train_classical_models.py and train_resnet18.py have completed:
    python evaluate_model_comparison.py
"""

