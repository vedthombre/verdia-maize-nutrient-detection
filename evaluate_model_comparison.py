def main():
    set_seed(SEED)
    RESULTS_DIR.mkdir(exist_ok=True)
    ARTIFACTS_DIR.mkdir(exist_ok=True)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    print(f"\n{'='*70}")
    print("  Model Comparison Evaluation — Verdia (Maize Nutrient Deficiency)")
    print(f"  Test set: 70 samples | Classes: {', '.join(CLASS_NAMES)}")
    print(f"  Device  : {device}")
    print(f"{'='*70}")

    # Verify all required files exist
    check_file(EFFICIENTNET_CKPT, "EfficientNet-B0 checkpoint")
    check_file(RESNET18_CKPT,     "ResNet18 checkpoint")
    check_file(SVM_PATH,          "SVM classifier")
    check_file(RF_PATH,           "Random Forest classifier")
    check_file(KNN_PATH,          "KNN classifier")
    check_file(SCALER_PATH,       "StandardScaler")

    # Common test DataLoader for CNN models
    test_ds     = MaizeLeafDataset(CSV_PATH, "test", transform=test_transform)
    test_loader = DataLoader(test_ds, batch_size=BATCH_SIZE,
                             shuffle=False, num_workers=NUM_WORKERS)
    print(f"\n  Test samples confirmed: {len(test_ds)}")

    all_metrics = {}   # model_name -> metrics dict

    # ──────────────────────────────────────────────────────────────────
    # E. EfficientNet-B0 (Experiment 5)
    # ──────────────────────────────────────────────────────────────────
    print(f"\n{'-'*70}")
    print("  [E] EfficientNet-B0 (Experiment 5 — deeper fine-tuned)")
    print(f"{'-'*70}")
    effnet = build_efficientnet_b0(
        num_classes=NUM_CLASSES,
        freeze_backbone=False,
        unfreeze_blocks=EFFICIENTNET_UNFREEZE_BLKS
    )
    effnet.load_state_dict(
        torch.load(EFFICIENTNET_CKPT, map_location=device, weights_only=True)
    )
    effnet = effnet.to(device)
    effnet.eval()

    t0 = time.time()
    eff_labels, eff_preds = run_cnn_inference(effnet, test_loader, device)
    eff_infer_time = time.time() - t0

    eff_metrics, eff_cm = compute_metrics_dict(
        "EfficientNet-B0", eff_labels, eff_preds, eff_infer_time
    )
    print_metrics(eff_metrics)

    # Reproducibility check against Exp5 reference
    acc_delta = abs(eff_metrics["test_accuracy"] - EFF_REF_ACC)
    f1_delta  = abs(eff_metrics["macro_f1"]      - EFF_REF_MACRO_F1)
    print(f"\n  Reproducibility check vs Exp5 reference:")
    print(f"    Accuracy Delta : {acc_delta:.2e}  "
          f"({'OK' if acc_delta < 1e-6 else 'MISMATCH — investigate'})")
    print(f"    Macro F1 Delta : {f1_delta:.2e}  "
          f"({'OK' if f1_delta < 1e-6 else 'MISMATCH — investigate'})")
    eff_metrics["exp5_reproducibility"] = {
        "reference_accuracy": EFF_REF_ACC,
        "reference_macro_f1": EFF_REF_MACRO_F1,
        "reference_weighted_f1": EFF_REF_WTD_F1,
        "accuracy_delta": acc_delta,
        "f1_delta": f1_delta,
        "reproduced": bool(acc_delta < 1e-6 and f1_delta < 1e-6),
    }

    all_metrics["EfficientNet-B0"] = eff_metrics
    del effnet

    # ──────────────────────────────────────────────────────────────────
    # D. ResNet18
    # ──────────────────────────────────────────────────────────────────
    print(f"\n{'-'*70}")
    print("  [D] ResNet18 (ImageNet pretrained, fully fine-tuned)")
    print(f"{'-'*70}")
    resnet = build_resnet18(num_classes=RESNET_CLASSES)
    resnet.load_state_dict(
        torch.load(RESNET18_CKPT, map_location=device, weights_only=True)
    )
    resnet = resnet.to(device)
    resnet.eval()

    # Load training time if available
    rn_train_time = None
    rn_history_path = RESULTS_DIR / "resnet18_comparison_training_history.json"
    if rn_history_path.exists():
        with open(rn_history_path) as f:
            rn_history = json.load(f)
        rn_train_time = rn_history.get("total_train_time_seconds")

    t0 = time.time()
    rn_labels, rn_preds = run_cnn_inference(resnet, test_loader, device)
    rn_infer_time = time.time() - t0

    rn_metrics, rn_cm = compute_metrics_dict(
        "ResNet18", rn_labels, rn_preds, rn_infer_time,
        train_time_s=rn_train_time
    )
    print_metrics(rn_metrics)

    # Confusion matrix
    plot_confusion_matrix(
        rn_cm,
        "Confusion Matrix — ResNet18 (Test Set)",
        RESULTS_DIR / "resnet18_confusion_matrix.png"
    )
    all_metrics["ResNet18"] = rn_metrics
    del resnet

    # ──────────────────────────────────────────────────────────────────
    # A/B/C: Classical models (SVM, RF, KNN)
    # Load test features (from cache or extract fresh)
    # ──────────────────────────────────────────────────────────────────
    print(f"\n{'-'*70}")
    print("  Loading classical model artifacts ...")
    print(f"{'-'*70}")

    X_test_raw, y_test = maybe_extract_test_features(device)

    with open(SCALER_PATH, "rb") as f:
        scaler = pickle.load(f)
    X_test_sc = scaler.transform(X_test_raw)   # scaled, no refit on test

    with open(SVM_PATH, "rb") as f:
        svm_clf = pickle.load(f)
    with open(RF_PATH, "rb") as f:
        rf_clf  = pickle.load(f)
    with open(KNN_PATH, "rb") as f:
        knn_clf = pickle.load(f)

    # Retrieve training time from val grid log if available
    classical_train_times = {}
    grid_log_path = ARTIFACTS_DIR / "comparison_val_grid_search.json"
    # Training times were not serialised in grid log; use None

    # ── A. SVM ────────────────────────────────────────────────────────
    print(f"\n{'-'*70}")
    print("  [A] SVM (EfficientNet-B0 features, RBF kernel, scaled)")
    print(f"{'-'*70}")
    t0 = time.time()
    svm_preds = svm_clf.predict(X_test_sc)
    svm_infer = time.time() - t0
    svm_metrics, svm_cm = compute_metrics_dict(
        "SVM", y_test.tolist(), svm_preds.tolist(), svm_infer
    )
    print_metrics(svm_metrics)
    plot_confusion_matrix(
        svm_cm,
        "Confusion Matrix — SVM (EfficientNet-B0 features, Test Set)",
        RESULTS_DIR / "svm_confusion_matrix.png"
    )
    all_metrics["SVM"] = svm_metrics

    # ── B. Random Forest ──────────────────────────────────────────────
    print(f"\n{'-'*70}")
    print("  [B] Random Forest (EfficientNet-B0 features, unscaled)")
    print(f"{'-'*70}")
    t0 = time.time()
    rf_preds = rf_clf.predict(X_test_raw)   # RF does not need scaling
    rf_infer = time.time() - t0
    rf_metrics, rf_cm = compute_metrics_dict(
        "Random Forest", y_test.tolist(), rf_preds.tolist(), rf_infer
    )
    print_metrics(rf_metrics)
    plot_confusion_matrix(
        rf_cm,
        "Confusion Matrix — Random Forest (EfficientNet-B0 features, Test Set)",
        RESULTS_DIR / "random_forest_confusion_matrix.png"
    )
    all_metrics["Random Forest"] = rf_metrics

    # ── C. KNN ────────────────────────────────────────────────────────
    print(f"\n{'-'*70}")
    print("  [C] KNN (EfficientNet-B0 features, scaled)")
    print(f"{'-'*70}")
    t0 = time.time()
    knn_preds = knn_clf.predict(X_test_sc)
    knn_infer = time.time() - t0
    knn_metrics, knn_cm = compute_metrics_dict(
        "KNN", y_test.tolist(), knn_preds.tolist(), knn_infer
    )
    print_metrics(knn_metrics)
    plot_confusion_matrix(
        knn_cm,
        "Confusion Matrix — KNN (EfficientNet-B0 features, Test Set)",
        RESULTS_DIR / "knn_confusion_matrix.png"
    )
    all_metrics["KNN"] = knn_metrics

    # ──────────────────────────────────────────────────────────────────
    # SAVE OUTPUTS
    # ──────────────────────────────────────────────────────────────────
    print(f"\n{'='*70}")
    print("  Saving comparison outputs ...")

    # JSON
    json_path = RESULTS_DIR / "model_comparison.json"
    with open(json_path, "w") as f:
        json.dump(all_metrics, f, indent=2)
    print(f"  JSON   : {json_path}")

    # CSV summary
    csv_path = RESULTS_DIR / "model_comparison.csv"
    csv_fields = [
        "model", "test_accuracy", "macro_precision", "macro_recall",
        "macro_f1", "weighted_f1",
        "inference_time_seconds", "inference_ms_per_sample",
        "train_time_seconds",
    ] + [f"{cls}_{metric}"
         for cls in CLASS_NAMES
         for metric in ("precision", "recall", "f1_score", "support")]

    with open(csv_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=csv_fields, extrasaction="ignore")
        writer.writeheader()
        for model_name, mets in all_metrics.items():
            row = {
                "model":                    model_name,
                "test_accuracy":            mets["test_accuracy"],
                "macro_precision":          mets["macro_precision"],
                "macro_recall":             mets["macro_recall"],
                "macro_f1":                 mets["macro_f1"],
                "weighted_f1":              mets["weighted_f1"],
                "inference_time_seconds":   mets["inference_time_seconds"],
                "inference_ms_per_sample":  mets["inference_ms_per_sample"],
                "train_time_seconds":       mets.get("train_time_seconds"),
            }
            for cls in CLASS_NAMES:
                for metric in ("precision", "recall", "f1_score", "support"):
                    row[f"{cls}_{metric}"] = mets["per_class"][cls][metric]
            writer.writerow(row)
    print(f"  CSV    : {csv_path}")

    # Bar-chart comparison figure
    plot_comparison(all_metrics, RESULTS_DIR / "model_comparison.png")

    # ──────────────────────────────────────────────────────────────────
    # SUMMARY TABLE (console)
    # ──────────────────────────────────────────────────────────────────
    print(f"\n{'='*70}")
    print("  SUMMARY — All Models on Test Set (n=70)")
    print(f"  {'Model':<22} {'Accuracy':>9} {'MacroF1':>9} {'WtdF1':>9}")
    print(f"  {'-'*22} {'-'*9} {'-'*9} {'-'*9}")
    ranked = sorted(all_metrics.items(),
                    key=lambda kv: kv[1]["macro_f1"], reverse=True)
    for model_name, mets in ranked:
        print(f"  {model_name:<22} "
              f"{mets['test_accuracy']:>8.1%}  "
              f"{mets['macro_f1']:>8.4f}  "
              f"{mets['weighted_f1']:>8.4f}")

    best_model = ranked[0][0]
    print(f"\n  Best macro F1 : {best_model} "
          f"({ranked[0][1]['macro_f1']:.4f})")
    print(f"{'='*70}\n")
    print("  NOTE: The test set contains only 70 images. Results reflect")
    print("  exploratory comparison on this split; no statistical significance")
    print("  claims are warranted.")
    print(f"{'='*70}\n")


if __name__ == "__main__":
    main()
