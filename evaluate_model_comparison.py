def set_seed(seed: int):
    import random
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def check_file(path: Path, label: str):
    if not path.exists():
        raise FileNotFoundError(
            f"Required {label} not found: {path}\n"
            "Ensure all training scripts have been run first."
        )


def plot_confusion_matrix(cm, title, save_path):
    fig, ax = plt.subplots(figsize=(7, 6))
    disp = ConfusionMatrixDisplay(cm, display_labels=CLASS_NAMES)
    disp.plot(ax=ax, cmap="Blues", values_format="d", colorbar=True)
    ax.set_title(title)
    plt.xticks(rotation=30, ha="right")
    fig.tight_layout()
    fig.savefig(save_path, dpi=150)
    plt.close(fig)
    print(f"  Saved: {save_path}")


def compute_metrics_dict(model_name, all_labels, all_preds,
                         inference_time_s, train_time_s=None):
    """
    Compute and return a structured metrics dictionary for one model.
    """
    n         = len(all_labels)
    correct   = sum(1 for y, p in zip(all_labels, all_preds) if y == p)
    test_acc  = correct / n

    report_dict = classification_report(
        all_labels, all_preds,
        target_names=CLASS_NAMES, output_dict=True, zero_division=0
    )
    macro_prec  = report_dict["macro avg"]["precision"]
    macro_rec   = report_dict["macro avg"]["recall"]
    macro_f1    = report_dict["macro avg"]["f1-score"]
    weighted_f1 = report_dict["weighted avg"]["f1-score"]
    cm          = confusion_matrix(all_labels, all_preds)

    metrics = {
        "model":              model_name,
        "test_accuracy":      test_acc,
        "correct_predictions": correct,
        "total_predictions":  n,
        "macro_precision":    macro_prec,
        "macro_recall":       macro_rec,
        "macro_f1":           macro_f1,
        "weighted_f1":        weighted_f1,
        "inference_time_seconds":   inference_time_s,
        "inference_ms_per_sample":  inference_time_s / n * 1000,
        "train_time_seconds": train_time_s,
        "per_class":          {},
        "confusion_matrix":   cm.tolist(),
        "test_sample_counts": {
            CLASS_NAMES[i]: int(Counter(all_labels).get(i, 0))
            for i in range(NUM_CLASSES)
        },
    }
    for name in CLASS_NAMES:
        metrics["per_class"][name] = {
            "precision": report_dict[name]["precision"],
            "recall":    report_dict[name]["recall"],
            "f1_score":  report_dict[name]["f1-score"],
            "support":   int(report_dict[name]["support"]),
        }
    return metrics, cm


def print_metrics(metrics: dict):
    print(f"  Accuracy   : {metrics['test_accuracy']:.4f} "
          f"({metrics['test_accuracy']:.1%})")
    print(f"  Macro Prec : {metrics['macro_precision']:.4f}")
    print(f"  Macro Rec  : {metrics['macro_recall']:.4f}")
    print(f"  Macro F1   : {metrics['macro_f1']:.4f}")
    print(f"  Wtd F1     : {metrics['weighted_f1']:.4f}")
    print(f"  Infer time : {metrics['inference_time_seconds']:.3f}s  "
          f"({metrics['inference_ms_per_sample']:.2f} ms/sample)")
    print(f"  Per-class:")
    for cls in CLASS_NAMES:
        pc = metrics["per_class"][cls]
        print(f"    {cls:12s}  P={pc['precision']:.3f}  "
              f"R={pc['recall']:.3f}  F1={pc['f1_score']:.3f}  "
              f"n={pc['support']}")


