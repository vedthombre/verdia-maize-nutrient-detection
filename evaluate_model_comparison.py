# CNN INFERENCE HELPER
# ──────────────────────────────────────────────────────────────────────
@torch.no_grad()
def run_cnn_inference(model, loader, device):
    model.eval()
    all_labels = []
    all_preds  = []
    for images, labels in loader:
        images = images.to(device)
        outputs = model(images)
        _, preds = outputs.max(1)
        all_labels.extend(labels.tolist())
        all_preds.extend(preds.cpu().tolist())
    return all_labels, all_preds


# ──────────────────────────────────────────────────────────────────────
# FEATURE EXTRACTOR FOR CLASSICAL MODELS
# ──────────────────────────────────────────────────────────────────────
@torch.no_grad()
def maybe_extract_test_features(device):
    """
    Load cached test features or extract them if cache is missing.
    Returns (X_test, y_test) as numpy arrays.
    """
    if TEST_FEATURES_PATH.exists():
        data   = np.load(TEST_FEATURES_PATH)
        X_test = data["features"]
        y_test = data["labels"]
        print(f"  Loaded cached test features: {X_test.shape}")
        return X_test, y_test

    print("  Test features not found in cache — extracting now ...")
    weights   = EfficientNet_B0_Weights.IMAGENET1K_V1
    extractor = models.efficientnet_b0(weights=weights)
    extractor.classifier = torch.nn.Identity()
    for p in extractor.parameters():
        p.requires_grad = False
    extractor.eval().to(device)

    test_ds     = MaizeLeafDataset(CSV_PATH, "test", transform=val_transform)
    test_loader = DataLoader(test_ds, batch_size=BATCH_SIZE,
                             shuffle=False, num_workers=NUM_WORKERS)
    all_feats, all_labels = [], []
    for images, labels in test_loader:
        feats = extractor(images.to(device))
        all_feats.append(feats.cpu().numpy())
        all_labels.append(labels.numpy())

    X_test = np.concatenate(all_feats, axis=0)
    y_test = np.concatenate(all_labels, axis=0)
    ARTIFACTS_DIR.mkdir(exist_ok=True)
    np.savez(TEST_FEATURES_PATH, features=X_test, labels=y_test)
    print(f"  Extracted and cached: {X_test.shape}")
    del extractor
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return X_test, y_test


