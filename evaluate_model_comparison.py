# COMPARISON BAR CHART
# ──────────────────────────────────────────────────────────────────────
def plot_comparison(all_metrics: dict, save_path: Path):
    """
    Bar chart showing test accuracy, macro F1 and weighted F1 for all
    five models side by side.
    """
    model_names  = list(all_metrics.keys())
    accuracies   = [all_metrics[m]["test_accuracy"]  for m in model_names]
    macro_f1s    = [all_metrics[m]["macro_f1"]       for m in model_names]
    weighted_f1s = [all_metrics[m]["weighted_f1"]    for m in model_names]

    x      = np.arange(len(model_names))
    width  = 0.25
    colors = ["#4C72B0", "#55A868", "#C44E52"]

    fig, ax = plt.subplots(figsize=(12, 6))
    bars1 = ax.bar(x - width,     accuracies,   width, label="Test Accuracy",
                   color=colors[0], alpha=0.87)
    bars2 = ax.bar(x,             macro_f1s,    width, label="Macro F1",
                   color=colors[1], alpha=0.87)
    bars3 = ax.bar(x + width,     weighted_f1s, width, label="Weighted F1",
                   color=colors[2], alpha=0.87)

    # Value labels above each bar
    for bars in (bars1, bars2, bars3):
        for bar in bars:
            h = bar.get_height()
            ax.annotate(
                f"{h:.3f}",
                xy=(bar.get_x() + bar.get_width() / 2, h),
                xytext=(0, 3), textcoords="offset points",
                ha="center", va="bottom", fontsize=8
            )

    ax.set_xticks(x)
    ax.set_xticklabels(model_names, rotation=15, ha="right", fontsize=10)
    ax.set_ylabel("Score", fontsize=11)
    ax.set_ylim(0, 1.10)
    ax.set_title(
        "Algorithm Comparison — Maize Leaf Nutrient Deficiency (Test Set, n=70)",
        fontsize=12, fontweight="bold"
    )
    ax.legend(fontsize=10)
    ax.grid(axis="y", alpha=0.35)
    ax.yaxis.set_major_formatter(
        matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:.0%}")
    )
    fig.tight_layout()
    fig.savefig(save_path, dpi=150)
    plt.close(fig)
    print(f"\n  Comparison chart saved: {save_path}")


